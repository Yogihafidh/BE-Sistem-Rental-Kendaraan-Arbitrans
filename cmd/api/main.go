package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	gin "github.com/gin-gonic/gin"
	goredis "github.com/redis/go-redis/v9"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"

	_ "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/docs" // docs is generated by Swag

	appConfig "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/configs"
	dbSqlc "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/database/sqlc"
	sharedDatabase "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/database"
	sharedJWT "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/jwt"
	sharedLogger "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/logger"
	sharedMiddleware "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/middleware"
	sharedMinIO "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/minio"
	sharedRedis "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/redis"
	sharedResponse "github.com/Yogihafidh/BE-Sistem-Rental-Kendaraan-Arbitrans/internal/shared/response"
)

// @title			Arbitrans API
// @version		1.0
// @description	Backend API for vehicle rental system
// @host			localhost:8080
// @BasePath		/api/v1
// @securityDefinitions.apikey	BearerAuth
// @in				header
// @name			Authorization
// @description		Type "Bearer" followed by a space and JWT token.
func main() {

	// 1. Load all Configuration
	cfg, err := appConfig.LoadConfig()
	if err != nil {
		fmt.Fprintf(os.Stderr, "FATAL: configuration failure: %v\n", err)
		os.Exit(1)
	}

	// 2. Initialize structured logging
	appLogger := sharedLogger.NewLogger(cfg.App.Env)
	appLogger.Info("Starting application",
		slog.String("app", cfg.App.Name),
		slog.String("env", cfg.App.Env),
		slog.String("port", cfg.App.Port),
	)

	// 3. Initialize JWT authentication manager
	sharedJWT.Init(cfg.JWT)

	// 4. Create root context
	ctx := context.Background()

	// 5. Setup PostgreSQL connection pool (Mandatory Core Dependency)
	pool, err := sharedDatabase.NewPostgresPool(ctx, cfg.DB)
	if err != nil {
		appLogger.Error("Failed to initialize database connection pool", slog.String("error", err.Error()))
		os.Exit(1)
	}
	defer pool.Close()
	appLogger.Info("Database connection pool established successfully",
		slog.Int("max_conns", int(cfg.DB.MaxConns)),
		slog.Int("min_conns", int(cfg.DB.MinConns)),
	)

	// 6. Setup Redis Client (Optional Infrastructure Dependency)
	var redisClient *goredis.Client
	if cfg.Redis.Enabled && cfg.Redis.Addr != "" {
		rc, err := sharedRedis.NewClient(ctx, cfg.Redis)
		if err != nil {
			appLogger.Warn("Redis connection failed; continuing without cache",
				slog.String("addr", cfg.Redis.Addr),
				slog.String("error", err.Error()),
			)
		} else {
			redisClient = rc
			defer redisClient.Close()
			appLogger.Info("Redis connection established", slog.String("addr", cfg.Redis.Addr))
		}
	}

	// 7. Setup MinIO Client (Optional/On-Demand Storage Dependency)
	var minioClient *sharedMinIO.Client
	if cfg.MinIO.Endpoint != "" {
		mc, err := sharedMinIO.NewClient(cfg.MinIO)
		if err != nil {
			appLogger.Warn("MinIO client initialization failed", slog.String("error", err.Error()))
		} else {
			minioClient = mc
			// Ensure default bucket exists with a short timeout
			ensureCtx, ensureCancel := context.WithTimeout(ctx, 3*time.Second)
			if bErr := minioClient.EnsureBucket(ensureCtx); bErr != nil {
				appLogger.Warn("MinIO bucket initialization failed; bucket may need to be created manually",
					slog.String("bucket", cfg.MinIO.Bucket),
					slog.String("error", bErr.Error()),
				)
			} else {
				appLogger.Info("MinIO client configured and bucket verified",
					slog.String("endpoint", cfg.MinIO.Endpoint),
					slog.String("bucket", cfg.MinIO.Bucket),
				)
			}
			ensureCancel()
		}

	}

	// 8. Instantiate SQLC query repository (Ready for module dependency injection)
	queries := dbSqlc.New(pool)
	_ = queries
	_ = minioClient
	_ = redisClient

	// 9. Setup Gin HTTP engine
	if cfg.App.IsProduction() {
		gin.SetMode(gin.ReleaseMode)
	} else {
		gin.SetMode(gin.DebugMode)
	}

	r := gin.New()

	// 10. Register foundational middlewares in correct order
	r.Use(sharedMiddleware.CORS(cfg.CORS))
	r.Use(sharedMiddleware.RequestLogger(appLogger))
	r.Use(sharedMiddleware.Recovery(appLogger))
	r.Use(sharedMiddleware.BodySizeLimit(10 << 20)) // 10 MB maximum request payload

	// 11. Health check endpoint (Accurate multi-component reporting)
	r.GET("/health", func(c *gin.Context) {
		pingCtx, cancel := context.WithTimeout(c.Request.Context(), cfg.App.ReadTimeout)
		defer cancel()

		dbHealthy := true
		dbStatus := "healthy"
		if pingErr := pool.Ping(pingCtx); pingErr != nil {
			dbHealthy = false
			dbStatus = "unreachable: " + pingErr.Error()
		}

		redisStatus := "disabled"
		redisHealthy := true
		if redisClient != nil {
			if rPingErr := redisClient.Ping(pingCtx).Err(); rPingErr != nil {
				redisHealthy = false
				redisStatus = "unreachable: " + rPingErr.Error()
			} else {
				redisStatus = "healthy"
			}
		}

		minioStatus := "not_configured"
		if minioClient != nil {
			minioStatus = "configured"
		}

		// If core database is down, system is DOWN (503 Service Unavailable)
		if !dbHealthy {
			sharedResponse.Error(c, http.StatusServiceUnavailable, "Database is unreachable", gin.H{
				"status":   "DOWN",
				"database": dbStatus,
				"redis":    redisStatus,
				"minio":    minioStatus,
				"env":      cfg.App.Env,
			})
			return
		}

		// If optional dependencies are degraded
		overallStatus := "UP"
		if !redisHealthy {
			overallStatus = "DEGRADED"
		}

		sharedResponse.Success(c, http.StatusOK, "System operational", gin.H{
			"status":   overallStatus,
			"database": dbStatus,
			"redis":    redisStatus,
			"minio":    minioStatus,
			"env":      cfg.App.Env,
		})
	})

	// 12. Register Swagger UI route
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// 13. API v1 group
	api := r.Group("/api/v1")
	api.GET("/ping", func(c *gin.Context) {
		sharedResponse.Success(c, http.StatusOK, "pong", nil)
	})

	// 14. Configure HTTP server with timeouts
	serverAddr := fmt.Sprintf(":%s", cfg.App.Port)
	srv := &http.Server{
		Addr:         serverAddr,
		Handler:      r,
		ReadTimeout:  cfg.App.ReadTimeout,
		WriteTimeout: cfg.App.WriteTimeout,
		IdleTimeout:  cfg.App.IdleTimeout,
	}

	// 15. Start HTTP server in a separate goroutine
	go func() {
		appLogger.Info("HTTP server listening", slog.String("addr", serverAddr))
		if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			appLogger.Error("HTTP server failed", slog.String("error", err.Error()))
			os.Exit(1)
		}
	}()

	// 16. Graceful application shutdown listening for OS signals
	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)
	sig := <-quit

	appLogger.Info("Shutdown signal received, shutting down gracefully...", slog.String("signal", sig.String()))

	shutdownCtx, shutdownCancel := context.WithTimeout(context.Background(), cfg.App.ShutdownTimeout)
	defer shutdownCancel()

	if err := srv.Shutdown(shutdownCtx); err != nil {
		appLogger.Error("Server forced to shutdown", slog.String("error", err.Error()))
	} else {
		appLogger.Info("HTTP server stopped gracefully")
	}

	appLogger.Info("Application shutdown completed")
}
